#:property PublishAot=false

// Writes Melville.Pdf.ReferenceDocuments/Infrastructure/KnownGenerators.g.cs: every reference document generator,
// listed explicitly so trimmed and AOT apps (the MAUI sample) can enumerate them without reflection.
// Rerun after adding a generator; KnownGeneratorsTest (Melville.Pdf.MauiGraphics.Tests) fails until you do.
// Run from Src:  ./.dotnet/dotnet run tools/ListReferenceGenerators.cs

using System.Text;
using Melville.Pdf.ReferenceDocuments.Infrastructure;

var types = GeneratorFactory.AllGenerators.Select(g => g.GetType())
    .OrderBy(t => t.FullName, StringComparer.Ordinal).ToList();
var code = new StringBuilder();
code.AppendLine("// <auto-generated> by Src/tools/ListReferenceGenerators.cs; do not edit. </auto-generated>");
code.AppendLine("namespace Melville.Pdf.ReferenceDocuments.Infrastructure;");
code.AppendLine();
code.AppendLine("/// <summary>Every reference document generator, without reflection (for trimmed and AOT apps).</summary>");
code.AppendLine("public static class KnownGenerators");
code.AppendLine("{");
code.AppendLine("    /// <summary>A new instance of each generator, ordered by type name.</summary>");
code.AppendLine("    public static IEnumerable<IPdfGenerator> All =>");
code.AppendLine("    [");
foreach (var type in types)
    code.AppendLine(System.Globalization.CultureInfo.InvariantCulture, $"        new global::{type.FullName!.Replace('+', '.')}(),");
code.AppendLine("    ];");
code.AppendLine("}");

var path = Path.GetFullPath(args.Length > 0 ? args[0] : "Melville.Pdf.ReferenceDocuments/Infrastructure/KnownGenerators.g.cs");
File.WriteAllText(path, code.ToString());
Console.WriteLine($"{types.Count} generators written to {path}");
